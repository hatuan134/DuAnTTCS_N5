-- History is retained only for authenticated users. Guest conversations remain ephemeral.
-- Treat these tables as personal information; back them up and restrict SQL access accordingly.
CREATE TABLE ai_chat_threads (
  id VARCHAR(36) PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  role VARCHAR(32) NOT NULL,
  title VARCHAR(160) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_ai_chat_threads_actor ON ai_chat_threads(user_id, role, updated_at DESC);

CREATE TABLE ai_chat_entries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  thread_id VARCHAR(36) NOT NULL REFERENCES ai_chat_threads(id) ON DELETE CASCADE,
  role VARCHAR(12) NOT NULL CHECK (role IN ('user', 'assistant')),
  content TEXT NOT NULL,
  blocks_json TEXT NOT NULL DEFAULT '[]',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_ai_chat_entries_thread ON ai_chat_entries(thread_id, id);
