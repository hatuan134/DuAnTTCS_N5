import test from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import ts from 'typescript'

const code = readFileSync(new URL('../src/features/ai-assistant/navigation.ts', import.meta.url), 'utf8')
const js = ts.transpileModule(code, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText
const exports = {}
new Function('exports', 'module', js)(exports, { exports })
const { allowedAiPath } = exports

test('catalog navigation accepts bounded verified filters for guests', () => {
  assert.equal(allowedAiPath('/catalog?keyword=Java&availableOnly=true', 'PUBLIC'), true)
  assert.equal(allowedAiPath('/catalog?keyword=Java%20Core', 'READER'), true)
  assert.equal(allowedAiPath('/catalog?keyword=Java&admin=true', 'PUBLIC'), false)
  assert.equal(allowedAiPath('/catalog?keyword=Java&keyword=PHP', 'PUBLIC'), false)
})
test('report range is permitted only to management and administrator', () => {
  const href = '/reports/loans?startDate=2026-10-01&endDate=2026-10-18'
  assert.equal(allowedAiPath(href, 'ADMIN'), true)
  assert.equal(allowedAiPath(href, 'LIBRARY_MANAGER'), true)
  assert.equal(allowedAiPath(href, 'READER'), false)
  assert.equal(allowedAiPath(href.replace('2026-10-18', '2027-10-18'), 'ADMIN'), false)
})
test('unsafe links are blocked even when generated by an LLM', () => {
  assert.equal(allowedAiPath('https://bad.example', 'ADMIN'), false)
  assert.equal(allowedAiPath('//bad.example/catalog', 'PUBLIC'), false)
  assert.equal(allowedAiPath('/admin/users', 'PUBLIC'), false)
})
test('publication year filtering is allowed and bounded for every role', () => {
  assert.equal(allowedAiPath('/catalog?publicationYear=2026', 'PUBLIC'), true)
  assert.equal(allowedAiPath('/catalog?keyword=Java&publicationYear=2026&availableOnly=true', 'READER'), true)
  assert.equal(allowedAiPath('/catalog?publicationYear=0', 'PUBLIC'), false)
  assert.equal(allowedAiPath('/catalog?publicationYear=2200', 'ADMIN'), false)
  assert.equal(allowedAiPath('/catalog?publicationYear=2026&publicationYear=2025', 'PUBLIC'), false)
  assert.equal(allowedAiPath('/catalog?publicationYear=abc', 'PUBLIC'), false)
})
